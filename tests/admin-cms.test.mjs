import assert from 'node:assert/strict';
import {stateOf,draftFrom} from '../admin/cms.mjs';
import {safeLink,safeImage,groupRows} from '../assets/js/cms-public.mjs';
assert.equal(stateOf({revision:1,published_revision:null}),'Draft');
assert.equal(stateOf({revision:2,published_revision:1}),'Unpublished edits');
assert.equal(stateOf({revision:2,published_revision:2}),'Published');
assert.equal(draftFrom({title:' X ',permission:true},'news').permission,false);
assert.equal(draftFrom({title:' X ',permission:true},'sponsor').permission,true);
assert.equal(draftFrom({title:' X ',date:'2027-05-29'},'event').date,'2027-05-29');
assert.equal(safeLink('javascript:alert(1)'),null);
assert.equal(safeLink('https://user:pass@example.com'),null);
assert.equal(safeLink('https://example.com/'),'https://example.com/');
assert.equal(safeImage('/assets/../private.png'),null);
assert.equal(safeImage('//evil.test/x.png'),null);
assert.equal(safeImage('/assets/test.svg'),null);
assert.equal(safeImage('/assets/test.png'),'/assets/test.png');
assert.deepEqual(groupRows([{kind:'__proto__',content:{title:'bad'}},{kind:'news',content:{title:'ok'}}]).news,[{title:'ok'}]);
assert.deepEqual(groupRows([{kind:'event',content:{title:'b',date:'2027-06-01'}},{kind:'event',content:{title:'a',date:'2027-05-29'}}]).event.map(x=>x.title),['a','b']);
console.log('CMS helper tests passed');
