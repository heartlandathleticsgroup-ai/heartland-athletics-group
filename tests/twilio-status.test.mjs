import assert from "node:assert/strict";
import {createHmac} from "node:crypto";
import {createStatusFixture,STATUS_URL,reduceStatus} from "../release/gmail/runtime/twilio-status-candidate.mjs";
const accountSid="AC"+"a".repeat(32),serviceSid="MG"+"b".repeat(32),number="+18005550123",authToken="a".repeat(32),dest="+12025550123";
let calls=[],fail=false;
const config={mode:"isolated-acceptance",accountSid,serviceSid,number,authToken,record:async e=>{calls.push(e);return !fail;}};
const route=createStatusFixture(config);
const request=(extra={},opts={})=>{
 const p=new URLSearchParams({AccountSid:accountSid,MessagingServiceSid:serviceSid,From:number,To:dest,MessageSid:"SM"+"c".repeat(32),MessageStatus:"delivered",...extra});
 if(opts.duplicate)p.append("MessageStatus","failed");
 const signature=createHmac("sha1",authToken).update(STATUS_URL+[...p.keys()].sort().map(k=>k+p.get(k)).join("")).digest("base64");
 return new Request(opts.url||STATUS_URL,{method:"POST",headers:{"content-type":"application/x-www-form-urlencoded","x-twilio-signature":opts.signature||signature},body:p});
};
assert.throws(()=>createStatusFixture({...config,mode:"production"}));
assert.equal((await route(request({}, {signature:"invalid"}))).status,403);
assert.equal((await route(request({}, {duplicate:true}))).status,400);
assert.equal((await route(request({}, {url:STATUS_URL+"?x=1"}))).status,403);
for(const extra of [{AccountSid:"AC"+"d".repeat(32)},{MessagingServiceSid:"MG"+"d".repeat(32)},{From:"+18005550124"},{To:"+442071234567"},{MessageSid:"invalid"}])assert.equal((await route(request(extra))).status,403);
assert.equal((await route(request({MessageStatus:"received"}))).status,400);
assert.equal(calls.length,0);
assert.equal((await route(request())).status,204);assert.deepEqual(calls[0],{messageSid:"SM"+"c".repeat(32),destination:dest,status:"delivered",errorCode:null});
assert.equal((await route(request({MessageStatus:"undelivered",ErrorCode:"21610"}))).status,204);assert.equal(calls.at(-1).errorCode,"21610");
fail=true;assert.equal((await route(request())).status,503);
assert.deepEqual(reduceStatus(null,"queued"),{status:"queued",review:false});
assert.deepEqual(reduceStatus("sent","queued"),{status:"sent",review:false});
assert.deepEqual(reduceStatus("sent","delivered"),{status:"delivered",review:false});
assert.deepEqual(reduceStatus("delivered","sent"),{status:"delivered",review:false});
assert.deepEqual(reduceStatus("delivered","failed"),{status:"delivered",review:true});
assert.deepEqual(reduceStatus("failed","failed"),{status:"failed",review:false});
console.log("PASS: isolated signed status receipt, identity binding, out-of-order state protection and failure handling; no provider calls");
